// Splat Cleanup: interactively filters a Gaussian Splat PLY to remove floaters and
// reduce splat count, one step at a time.
//
// Workflow: Load a .ply once (data stays resident in memory), then apply filter steps
// individually — each step reports what it dropped and refines a running keep-mask.
// Write the current result to a new .ply at any point, bake it with the standard asset
// creator (Tools > Gaussian Splats), and inspect it in the scene before continuing.
//
// The heavy SOR (KNN) step runs as chunked background jobs so the editor stays
// responsive and can be cancelled mid-run. Output rows are copied verbatim from the
// input, so surviving splats are bit-exact (SH included).

